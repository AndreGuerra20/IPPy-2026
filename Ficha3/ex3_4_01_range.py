# Analise o resultado dos comandos em Python.

print('(a)', tuple(range(10)))
print('(b)', tuple(range(5, 10)))
print('(c)', tuple(range(-10, 10, 2)))
print('(d)', tuple(range(10, 0, -3)))
print('(e)', tuple(range(-10)))         # tuplo vazio: o início (0) já é maior que o fim
print('(f)', tuple(range(-10, 1)))
print('(g)', list(range(10)))
print('(h)', list(range(5, 10)))
print('(i)', [i * 0 for i in range(5)])
print('(j)', [i * 4 for i in range(5)])
print('(k)', [i ** 2 for i in range(11)])
print('(l)', 4 * tuple(range(5, 10)))
