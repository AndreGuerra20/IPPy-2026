# Usando o módulo math, determine o resultado das expressões matemáticas em Python.
import math

print('(a)', math.sqrt(9) ** round(2.6))
print('(b)', math.factorial(10))
print('(c)', math.exp(3 * math.log(2)))
print('(d)', round(4 * math.cos(math.pi / 4)))
print('(e)', math.log(math.e) + math.sqrt(25))
print('(f)', abs(math.log10(0.0001)))
print('(g)', 1 / math.sqrt(2 * math.pi))
print('(h)', math.sin(math.radians(45)) ** 2)     # o seno recebe radianos
print('(i)', math.gcd(12, 20))                    # mdc
print('(j)', round(math.pi))
print('(k)', round(math.pi, 4))
print('(l)', math.ceil(5.6) + math.floor(5.6))
print('(m)', math.ceil(-5.6) + math.floor(-5.6))
print('(n)', abs(3 - 4j) + math.factorial(3))    # abs de um complexo é o módulo
print('(o)', math.atan(1) / math.pi)
